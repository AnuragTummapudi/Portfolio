const skillNameIcons = Object.fromEntries(
  skillGroups.flatMap((group) => group.skills.map((skill) => [skill.name, skill.icon])),
);

export function iconForTag(tag: string) {
  return tagAliases[tag] ?? skillNameIcons[tag] ?? "code";
}

export function SkillIcon({ icon, className }: { icon: string; className?: string }) {
  const Icon = skillIcons[icon] ?? Code2;
  const color = skillIconColors[icon];
  return <Icon className={className} style={color ? { color } : undefined} aria-hidden="true" />;
}
